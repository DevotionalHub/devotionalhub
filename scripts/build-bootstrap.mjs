import { readdir, readFile, writeFile } from 'node:fs/promises';
import { basename } from 'node:path';
const migrationsDirectory = new URL('../supabase/migrations/', import.meta.url);
const outputFile = new URL('../supabase/bootstrap.sql', import.meta.url);
const seedFile = new URL('../supabase/seed.sql', import.meta.url);

const migrationFiles = (await readdir(migrationsDirectory))
  .filter((file) => /^\d+_[a-z0-9_]+\.sql$/.test(file))
  .sort();

if (migrationFiles.length === 0) {
  throw new Error('No Supabase migration files were found.');
}

const sections = [
  '-- DevotionalHub hosted Supabase bootstrap',
  '-- Generated by: npm run backend:bootstrap-file',
  '-- Run this entire file ONCE in Supabase Dashboard -> SQL Editor.',
  '-- It applies the version-controlled migrations and records their versions.',
  '',
  'begin;',
];

const appliedMigrations = [];

for (const file of migrationFiles) {
  const match = /^(\d+)_([a-z0-9_]+)\.sql$/.exec(file);
  if (!match) continue;

  const [, version, name] = match;
  const sql = await readFile(new URL(file, migrationsDirectory), 'utf8');
  sections.push('', `-- >>> ${file}`, sql.trim(), `-- <<< ${file}`);
  appliedMigrations.push({ version, name });
}

const seed = await readFile(seedFile, 'utf8');
sections.push('', '-- >>> seed.sql', seed.trim(), '-- <<< seed.sql');

sections.push(
  '',
  '-- Keep future Supabase CLI pushes in sync with this dashboard bootstrap.',
  'create schema if not exists supabase_migrations;',
  'create table if not exists supabase_migrations.schema_migrations (',
  '  version text not null primary key',
  ');',
  'alter table supabase_migrations.schema_migrations add column if not exists statements text[];',
  'alter table supabase_migrations.schema_migrations add column if not exists name text;'
);

for (const { version, name } of appliedMigrations) {
  sections.push(
    `insert into supabase_migrations.schema_migrations (version, name, statements)`,
    `values ('${version}', '${name}', null)`,
    `on conflict (version) do update set name = excluded.name;`
  );
}

sections.push('', 'commit;', '');
await writeFile(outputFile, sections.join('\n'), 'utf8');

console.log(`Generated ${basename(outputFile.pathname)} from ${migrationFiles.length} migrations.`);
